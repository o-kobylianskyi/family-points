import static org.junit.jupiter.api.Assertions.*;

/** B-B-04. Isolated PG18 QA-only FK tables, never a production restore. */
@Testcontainers
class DisposableFinancialTargetRehearsalPostgresTest {
    @Container static final PostgreSQLContainer DB =
            new PostgreSQLContainer("postgres:18-alpine")
                    .withDatabaseName("finance_target_qa")
                    .withUsername("qa").withPassword("qa");

    private static final ObjectMapper JSON=new ObjectMapper();
    private static final String SOURCE="""
            {
             "TASK_DEFINITIONS":[{"id":11,"family_id":17}],
             "TASK_EXECUTIONS":[{"id":21,"member_id":3,"task_definition_id":11}],
             "REWARD_DEFINITIONS":[{"id":31,"family_id":17}],
             "REWARD_PURCHASES":[{"id":41,"member_id":3,"reward_definition_id":31,
                  "point_type_id":51,"price_amount":4}],
             "POINT_TYPES":[{"id":51,"family_id":17,"code":"POINTS"}],
             "POINT_LEDGER":[
               {"id":61,"member_id":3,"point_type_id":51,"amount":5,"type":"EARN",
                "source_type":"TASK","source_id":21},
               {"id":62,"member_id":3,"point_type_id":51,"amount":-4,"type":"SPEND",
                "source_type":"REWARD_PURCHASE","source_id":41},
               {"id":63,"member_id":3,"point_type_id":51,"amount":2,"type":"EARN",
                "source_type":"MANUAL","source_id":null}
             ]
            }
            """;
    private record Fixture(JdbcTemplate db,DataSourceTransactionManager manager,
                           long targetFamily,long member,long currency,long neighborFamily) {
        DisposableFinancialTargetRehearsal consumer() {
            return new DisposableFinancialTargetRehearsal(db,manager);
        }
        DisposableRestoreFinancialDependencyPreflight.Mapping mapping() {
            return new DisposableRestoreFinancialDependencyPreflight.Mapping(
                    Map.of(3L,member),Map.of(51L,currency),
                    Map.of(11L,targetFamily*10000L+11L),
                    Map.of(31L,targetFamily*10000L+31L),
                    Map.of(41L,targetFamily*10000L+41L));
        }
        long rows(String table) {
            if(!Set.of("qa_restore_tasks","qa_restore_rewards",
                    "qa_restore_executions","qa_restore_purchases","qa_restore_ledger").contains(table))
                throw new IllegalArgumentException("QA_TABLE_INVALID");
            return db.queryForObject("SELECT count(*) FROM "+table+
                    " WHERE target_family=?",Long.class,targetFamily);
        }
    }
    private static Fixture setup() {
        var ds=new DriverManagerDataSource(
                DB.getJdbcUrl(),DB.getUsername(),DB.getPassword());
        Flyway.configure().dataSource(ds).locations("classpath:db/migration")
                .load().migrate();
        var db=new JdbcTemplate(ds);
        // Explicit FK relationships are in temporary QA tables only. All
        // source tables and all real financial event data stay untouched.
        db.execute("""
            CREATE TABLE IF NOT EXISTS qa_restore_tasks (
                id bigint PRIMARY KEY,target_family bigint NOT NULL REFERENCES families(id))
            """);
        db.execute("""
            CREATE TABLE IF NOT EXISTS qa_restore_executions (
                id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                target_family bigint NOT NULL REFERENCES families(id),
                source_execution_id bigint NOT NULL,
                member_id bigint NOT NULL REFERENCES family_members(id),
                task_id bigint NOT NULL REFERENCES qa_restore_tasks(id),
                UNIQUE(target_family,source_execution_id))
            """);
        db.execute("""
            CREATE TABLE IF NOT EXISTS qa_restore_rewards (
                id bigint PRIMARY KEY,target_family bigint NOT NULL REFERENCES families(id))
            """);
        db.execute("""
            CREATE TABLE IF NOT EXISTS qa_restore_purchases (
                id bigint PRIMARY KEY,
                target_family bigint NOT NULL REFERENCES families(id),
                member_id bigint NOT NULL REFERENCES family_members(id),
                reward_id bigint NOT NULL REFERENCES qa_restore_rewards(id),
                point_type_id bigint NOT NULL REFERENCES point_types(id),
                price_amount int NOT NULL CHECK (price_amount>0))
            """);
        db.execute("""
            CREATE TABLE IF NOT EXISTS qa_restore_ledger (
                id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                target_family bigint NOT NULL REFERENCES families(id),
                source_row_id bigint NOT NULL,
                member_id bigint NOT NULL REFERENCES family_members(id),
                point_type_id bigint NOT NULL REFERENCES point_types(id),
                amount int NOT NULL CHECK (amount<>0),
                source_type varchar(40) NOT NULL,
                source_id bigint,
                UNIQUE(target_family,source_row_id))
            """);
        long neighbor=db.queryForObject(
                "INSERT INTO families(name) VALUES (?) RETURNING id",
                Long.class,"Unrelated "+UUID.randomUUID());
        long family=db.queryForObject(
                "INSERT INTO families(name) VALUES (?) RETURNING id",
                Long.class,"Finance target "+UUID.randomUUID());
        long role=db.queryForObject("""
                INSERT INTO family_roles(family_id,code,name,system_role)
                VALUES (?,'PARENT','Parent',true) RETURNING id
                """,Long.class,family);
        long member=db.queryForObject("""
                INSERT INTO family_members(family_id,family_role_id,name,active,member_type)
                VALUES (?,?,'Synthetic',true,'PARENT') RETURNING id
                """,Long.class,family,role);
        long currency=db.queryForObject("""
                INSERT INTO point_types(family_id,code,name,active,sort_order)
                VALUES (?,'POINTS','Points',true,0) RETURNING id
                """,Long.class,family);
        return new Fixture(db,new DataSourceTransactionManager(ds),
                family,member,currency,neighbor);
    }
    private static JsonNode source() throws Exception {return JSON.readTree(SOURCE);}
    private static void assertEmpty(Fixture f) {
        for(String table:List.of("qa_restore_tasks","qa_restore_rewards",
                "qa_restore_purchases","qa_restore_ledger"))
            assertEquals(0L,f.rows(table),table);
    }

    @Test void fullMappedGraphCreatesFourCategoryTablesAndVerifiedBalance()
            throws Exception {
        var f=setup();
        var result=f.consumer().apply(source(),17,f.targetFamily,f.mapping(),0);
        assertEquals(1,result.definitions());
        assertEquals(1,result.rewards());
        assertEquals(1,result.purchases());
        assertEquals(3,result.ledgerRows());
        assertEquals(Map.of(f.member+":"+f.currency,3L),result.balances());
        assertEquals(1L,f.rows("qa_restore_tasks"));
        assertEquals(1L,f.rows("qa_restore_rewards"));
        assertEquals(1L,f.rows("qa_restore_executions"));
        assertEquals(1L,f.rows("qa_restore_purchases"));
        assertEquals(3L,f.rows("qa_restore_ledger"));
        assertEquals(f.mapping().purchases().get(41L),f.db.queryForObject("""
                SELECT source_id FROM qa_restore_ledger
                WHERE target_family=? AND source_type='REWARD_PURCHASE'
                """,Long.class,f.targetFamily));
        long targetExecution=result.executionIds().get(21L);
        assertNotEquals(21L,targetExecution);
        assertEquals(targetExecution,f.db.queryForObject("""
                SELECT source_id FROM qa_restore_ledger
                WHERE target_family=? AND source_type='TASK'
                """,Long.class,f.targetFamily));
        assertEquals(f.mapping().tasks().get(11L),f.db.queryForObject("""
                SELECT task_id FROM qa_restore_executions WHERE id=?
                """,Long.class,targetExecution));
        assertEquals(f.member,f.db.queryForObject("""
                SELECT member_id FROM qa_restore_executions WHERE id=?
                """,Long.class,targetExecution));
        assertEquals(0L,f.db.queryForObject(
                "SELECT count(*) FROM qa_restore_ledger WHERE target_family=?",
                Long.class,f.neighborFamily));
        assertThrows(SecurityException.class,()->f.consumer().apply(
                source(),17,f.targetFamily,f.mapping(),0));
        assertEquals(3L,f.rows("qa_restore_ledger"));
    }

    @Test void eachInjectedFailureRollsBackAllTablesAndFreshConsumerMayRetry()
            throws Exception {
        for(int stage=1;stage<=4;stage++) {
            var f=setup();
            final int step=stage;
            assertThrows(IllegalStateException.class,()->f.consumer().apply(
                    source(),17,f.targetFamily,f.mapping(),step));
            assertEmpty(f);
            var restored=f.consumer().apply(source(),17,f.targetFamily,f.mapping(),0);
            assertEquals(3,restored.ledgerRows());
            assertEquals(3L,f.rows("qa_restore_ledger"));
        }
    }

    @Test void tamperedSourceOrForeignTargetReferencesNeverPartiallyWrite()
            throws Exception {
        var f=setup();
        var wrongPrice=JSON.readTree(SOURCE.replace(
                "\"amount\":-4","\"amount\":-3"));
        assertThrows(SecurityException.class,()->f.consumer().apply(
                wrongPrice,17,f.targetFamily,f.mapping(),0));
        assertEmpty(f);
        var existing=f.mapping();
        var foreign=new DisposableRestoreFinancialDependencyPreflight.Mapping(
                Map.of(3L,Long.MAX_VALUE),existing.currencies(),
                existing.tasks(),existing.rewards(),existing.purchases());
        assertThrows(SecurityException.class,()->f.consumer().apply(
                source(),17,f.targetFamily,foreign,0));
        assertEmpty(f);
        var wrongCurrency=new DisposableRestoreFinancialDependencyPreflight.Mapping(
                existing.members(),Map.of(51L,Long.MAX_VALUE),
                existing.tasks(),existing.rewards(),existing.purchases());
        assertThrows(SecurityException.class,()->f.consumer().apply(
                source(),17,f.targetFamily,wrongCurrency,0));
        assertEmpty(f);
        f.db.update("UPDATE families SET data_epoch=1 WHERE id=?",f.targetFamily);
        assertThrows(SecurityException.class,()->f.consumer().apply(
                source(),17,f.targetFamily,f.mapping(),0));
        assertEmpty(f);
    }

    @Test void missingExecutionParentCannotLeaveAnyTargetRecords() throws Exception {
        var f=setup();
        var missing=JSON.readTree(SOURCE.replace(
                "\"task_definition_id\":11","\"task_definition_id\":999"));
        assertThrows(SecurityException.class,()->f.consumer().apply(
                missing,17,f.targetFamily,f.mapping(),0));
        assertEmpty(f);
        var orphan=JSON.readTree(SOURCE.replace(
                "\"source_type\":\"TASK\",\"source_id\":21",
                "\"source_type\":\"TASK\",\"source_id\":999"));
        assertThrows(SecurityException.class,()->f.consumer().apply(
                orphan,17,f.targetFamily,f.mapping(),0));
        assertEmpty(f);
    }

    @Test void simultaneousDuplicateConsumersCommitAtMostOnce() throws Exception {
        var f=setup();
        var executor=java.util.concurrent.Executors.newFixedThreadPool(2);
        var latch=new java.util.concurrent.CountDownLatch(1);
        try {
            List<java.util.concurrent.Future<Boolean>> attempts=new ArrayList<>();
            for(int i=0;i<2;i++) attempts.add(executor.submit(()->{
                latch.await();
                try {
                    f.consumer().apply(source(),17,f.targetFamily,f.mapping(),0);
                    return true;
                }catch(SecurityException reject){return false;}
            }));
            latch.countDown();
            int successes=0;
            for(var attempt:attempts)
                if(attempt.get(30,java.util.concurrent.TimeUnit.SECONDS))successes++;
            assertEquals(1,successes);
            assertEquals(1L,f.rows("qa_restore_purchases"));
            assertEquals(3L,f.rows("qa_restore_ledger"));
        }finally {executor.shutdownNow();}
    }
}
