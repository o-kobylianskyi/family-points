-- Existing accounts remain usable; only new password registrations require verification.
ALTER TABLE user_accounts ADD COLUMN email VARCHAR(254);
ALTER TABLE user_accounts ADD COLUMN email_verified_at TIMESTAMPTZ;
CREATE UNIQUE INDEX uq_user_accounts_email_lower ON user_accounts (lower(email)) WHERE email IS NOT NULL;

CREATE TABLE account_email_tokens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL REFERENCES user_accounts(id) ON DELETE CASCADE,
    token_hash VARCHAR(64) NOT NULL UNIQUE,
    purpose VARCHAR(24) NOT NULL CHECK (purpose IN ('VERIFY_EMAIL', 'RESET_PASSWORD')),
    expires_at TIMESTAMPTZ NOT NULL,
    consumed_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_account_email_tokens_account ON account_email_tokens (account_id, purpose, created_at DESC);
