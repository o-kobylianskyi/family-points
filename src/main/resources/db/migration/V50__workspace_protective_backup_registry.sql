-- BKL-BACKUP-001: metadata only. This does NOT create backup bytes or enable reset.
CREATE TABLE workspace_protective_backups (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  snapshot_id UUID NOT NULL UNIQUE,
  workspace_id BIGINT NOT NULL REFERENCES families(id) ON DELETE RESTRICT,
  operation_id UUID NOT NULL,
  requested_by_member_id BIGINT NOT NULL REFERENCES family_members(id) ON DELETE RESTRICT,
  data_epoch BIGINT NOT NULL CHECK (data_epoch >= 0),
  reset_mode VARCHAR(12) NOT NULL CHECK (reset_mode IN ('FULL','SELECTIVE')),
  selected_categories_json TEXT NOT NULL,
  source_digest CHAR(64) NOT NULL CHECK (source_digest ~ '^[0-9a-f]{64}$'),
  schema_version VARCHAR(80) NOT NULL,
  state VARCHAR(24) NOT NULL DEFAULT 'REQUESTED'
    CHECK (state IN ('REQUESTED','BACKING_UP','VERIFIED','AUTHORIZED_FOR_RESET',
                    'RESET_COMPLETED','BLOCKED','FAILED','EXPIRED')),
  storage_key TEXT,
  encrypted BOOLEAN NOT NULL DEFAULT FALSE,
  manifest_sha256 CHAR(64),
  restore_verified_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  expires_at TIMESTAMPTZ NOT NULL DEFAULT (CURRENT_TIMESTAMP + INTERVAL '30 days'),
  verified_at TIMESTAMPTZ,
  finished_at TIMESTAMPTZ,
  failure_code VARCHAR(100),
  CONSTRAINT uq_protective_backup_workspace_operation UNIQUE(workspace_id,operation_id),
  CONSTRAINT ck_protective_backup_30_days CHECK (expires_at >= created_at + INTERVAL '30 days'),
  CONSTRAINT ck_protective_backup_verified CHECK (
    state NOT IN ('VERIFIED','AUTHORIZED_FOR_RESET','RESET_COMPLETED')
    OR (encrypted AND storage_key IS NOT NULL AND manifest_sha256 IS NOT NULL
        AND restore_verified_at IS NOT NULL AND verified_at IS NOT NULL))
);
CREATE INDEX idx_protective_backup_workspace_created
  ON workspace_protective_backups(workspace_id,created_at DESC);
CREATE INDEX idx_protective_backup_expiry
  ON workspace_protective_backups(expires_at) WHERE state NOT IN ('EXPIRED','RESET_COMPLETED');
-- Storage deletion / 30-day lifecycle must be performed by an audited independent worker.
-- No backup status, including VERIFIED, authorizes the currently disabled HTTP execute.
