-- Targeted invitation to an EXISTING family member: never insert a second family_members row.
CREATE TABLE member_email_invitations (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  workspace_id BIGINT NOT NULL REFERENCES families(id),
  member_id BIGINT NOT NULL REFERENCES family_members(id),
  invited_email VARCHAR(254) NOT NULL,
  issued_by_account_id BIGINT NOT NULL REFERENCES user_accounts(id),
  token_hash CHAR(64) NOT NULL UNIQUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  expires_at TIMESTAMPTZ NOT NULL,
  consumed_at TIMESTAMPTZ,
  revoked_at TIMESTAMPTZ,
  CONSTRAINT ck_member_email_invite_expiry CHECK (expires_at > created_at)
);
CREATE INDEX idx_member_email_invites_member ON member_email_invitations(member_id, created_at DESC);
