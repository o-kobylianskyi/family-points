-- Child-originated wishes for new tasks. No reward is created or awarded here.
CREATE TABLE task_suggestions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  workspace_id BIGINT NOT NULL REFERENCES families(id),
  requested_by_member_id BIGINT NOT NULL REFERENCES family_members(id),
  title VARCHAR(150) NOT NULL,
  description VARCHAR(1000) NOT NULL DEFAULT '',
  status VARCHAR(16) NOT NULL DEFAULT 'PENDING'
    CHECK (status IN ('PENDING','APPROVED','REJECTED')),
  reviewed_by_member_id BIGINT REFERENCES family_members(id),
  reviewed_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_task_suggestions_workspace_status ON task_suggestions(workspace_id,status,created_at DESC);
