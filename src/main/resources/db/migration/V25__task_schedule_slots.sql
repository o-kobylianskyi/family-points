-- Schedule slots are reusable rules, not generated daily task instances.
-- Existing recurring tasks remain represented by their implicit default slot.
CREATE TABLE task_schedule_slots (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_definition_id BIGINT NOT NULL REFERENCES task_definitions(id) ON DELETE CASCADE,
    slot_key VARCHAR(40) NOT NULL,
    scheduled_time TIME,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT uq_task_schedule_slot_key UNIQUE(task_definition_id, slot_key),
    CONSTRAINT chk_task_schedule_slot_key CHECK (length(trim(slot_key)) > 0)
);
CREATE INDEX idx_task_schedule_slots_definition ON task_schedule_slots(task_definition_id);
