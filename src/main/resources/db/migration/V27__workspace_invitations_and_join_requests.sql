-- Workspace-scoped join flow foundation. No public endpoint is enabled by this migration.
-- Only SHA-256 token digests should be stored in token_hash, never invitation secrets.

CREATE TABLE workspace_invitations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workspace_id BIGINT NOT NULL REFERENCES families(id),
    created_by_account_id BIGINT NOT NULL REFERENCES user_accounts(id),
    token_hash CHAR(64) NOT NULL,
    invited_email VARCHAR(320),
    member_role_id BIGINT REFERENCES family_roles(id),
    max_uses INTEGER NOT NULL DEFAULT 1,
    use_count INTEGER NOT NULL DEFAULT 0,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    revoked_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_workspace_invitations_token_hash UNIQUE (token_hash),
    CONSTRAINT ck_workspace_invitation_uses CHECK (max_uses > 0 AND use_count >= 0 AND use_count <= max_uses),
    CONSTRAINT ck_workspace_invitation_expiry CHECK (expires_at > created_at)
);

CREATE INDEX idx_workspace_invitations_workspace
    ON workspace_invitations (workspace_id, expires_at);

CREATE TABLE workspace_join_codes (
    workspace_id BIGINT PRIMARY KEY REFERENCES families(id),
    code_hash CHAR(64) NOT NULL UNIQUE,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    rotated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE workspace_join_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workspace_id BIGINT NOT NULL REFERENCES families(id),
    requester_account_id BIGINT NOT NULL REFERENCES user_accounts(id),
    status VARCHAR(16) NOT NULL DEFAULT 'PENDING',
    requested_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    reviewed_at TIMESTAMP WITH TIME ZONE,
    reviewed_by_account_id BIGINT REFERENCES user_accounts(id),
    CONSTRAINT ck_workspace_join_request_status
        CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED', 'CANCELLED')),
    CONSTRAINT ck_workspace_join_request_review
        CHECK ((status = 'PENDING' AND reviewed_at IS NULL AND reviewed_by_account_id IS NULL)
            OR (status <> 'PENDING'))
);

CREATE UNIQUE INDEX uk_workspace_join_requests_pending
    ON workspace_join_requests (workspace_id, requester_account_id)
    WHERE status = 'PENDING';

CREATE INDEX idx_workspace_join_requests_queue
    ON workspace_join_requests (workspace_id, status, requested_at);

-- Explicit acceptance ledger permits idempotent invitation redemption and future audit.
CREATE TABLE workspace_invitation_redemptions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invitation_id BIGINT NOT NULL REFERENCES workspace_invitations(id),
    account_id BIGINT NOT NULL REFERENCES user_accounts(id),
    membership_id BIGINT REFERENCES account_workspace_memberships(id),
    redeemed_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_workspace_invitation_redemption_account UNIQUE (invitation_id, account_id)
);

-- Short-lived server-side invite context survives password signup and external OIDC redirects.
-- Store a digest of the random browser handle; never persist plaintext invitation tokens.
CREATE TABLE pending_invitation_sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    handle_hash CHAR(64) NOT NULL UNIQUE,
    invitation_id BIGINT NOT NULL REFERENCES workspace_invitations(id),
    account_id BIGINT REFERENCES user_accounts(id),
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    consumed_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_pending_invitation_session_expiry CHECK (expires_at > created_at)
);

CREATE INDEX idx_pending_invitation_sessions_expiry
    ON pending_invitation_sessions (expires_at);
