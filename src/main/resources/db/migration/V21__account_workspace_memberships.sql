-- Phase 1: additive global-account membership foundation.
-- Preserve user_accounts.family_member_id and legacy security until services
-- explicitly switch to context-selected memberships in a later migration.
-- A single account can be linked to several distinct workspace members.
CREATE TABLE account_workspace_memberships (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL REFERENCES user_accounts(id) ON DELETE RESTRICT,
    family_member_id BIGINT NOT NULL REFERENCES family_members(id) ON DELETE RESTRICT,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_account_workspace_memberships_member UNIQUE (family_member_id),
    CONSTRAINT uq_account_workspace_memberships_pair UNIQUE (account_id, family_member_id)
);

CREATE INDEX idx_account_workspace_memberships_account
    ON account_workspace_memberships(account_id);

-- Backfill only identity links, not private family data.
INSERT INTO account_workspace_memberships (account_id, family_member_id)
SELECT id, family_member_id
FROM user_accounts
WHERE family_member_id IS NOT NULL;

