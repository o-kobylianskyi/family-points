-- Additive first step toward global identities without a mandatory first family.
-- Existing accounts, primary-member links, and memberships remain unchanged.
ALTER TABLE user_accounts ALTER COLUMN family_member_id DROP NOT NULL;

-- External identities are verified by provider+subject, never linked by email alone.
CREATE TABLE account_external_identities (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL REFERENCES user_accounts(id) ON DELETE CASCADE,
    provider VARCHAR(40) NOT NULL,
    provider_subject VARCHAR(255) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_external_provider_subject UNIQUE (provider, provider_subject),
    CONSTRAINT uq_external_account_provider UNIQUE (account_id, provider),
    CONSTRAINT ck_external_provider_not_blank CHECK (length(trim(provider)) > 0),
    CONSTRAINT ck_external_subject_not_blank CHECK (length(trim(provider_subject)) > 0)
);
CREATE INDEX idx_external_identities_account ON account_external_identities(account_id);

