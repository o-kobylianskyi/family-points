-- BKL-002 foundation: durable, workspace-scoped reset audit and replay identity.
-- This migration does NOT delete data or authorize reset execution.
CREATE TABLE workspace_reset_operations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workspace_id BIGINT NOT NULL REFERENCES families(id) ON DELETE RESTRICT,
    operation_id UUID NOT NULL,
    requested_by_member_id BIGINT NOT NULL REFERENCES family_members(id) ON DELETE RESTRICT,
    selected_categories_json TEXT NOT NULL,
    snapshot_digest CHAR(64) NOT NULL,
    status VARCHAR(24) NOT NULL DEFAULT 'PREPARED'
        CHECK (status IN ('PREPARED','CONFIRMED','SUCCEEDED','FAILED','CANCELLED')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    confirmed_at TIMESTAMPTZ,
    finished_at TIMESTAMPTZ,
    outcome_json TEXT,
    CONSTRAINT uq_workspace_reset_operation UNIQUE(workspace_id, operation_id),
    CONSTRAINT ck_reset_digest_hex CHECK (snapshot_digest ~ '^[0-9a-f]{64}$'),
    CONSTRAINT ck_reset_confirmed_timestamp CHECK (
        status NOT IN ('CONFIRMED','SUCCEEDED') OR confirmed_at IS NOT NULL
    ),
    CONSTRAINT ck_reset_finished_timestamp CHECK (
        status NOT IN ('SUCCEEDED','FAILED','CANCELLED') OR finished_at IS NOT NULL
    )
);
CREATE INDEX idx_workspace_reset_audit_workspace
    ON workspace_reset_operations(workspace_id, created_at DESC);
