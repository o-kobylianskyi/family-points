-- Private template definitions are not executable tasks/rewards and carry no ledger history.
CREATE TABLE workspace_private_templates (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workspace_id BIGINT NOT NULL REFERENCES families(id) ON DELETE CASCADE,
    kind VARCHAR(20) NOT NULL CHECK (kind IN ('TASK','REWARD','EVENT')),
    title VARCHAR(150) NOT NULL,
    definition_json TEXT NOT NULL,
    catalog_code VARCHAR(80),
    catalog_version INTEGER,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT private_template_catalog_pair CHECK (
        (catalog_code IS NULL AND catalog_version IS NULL)
        OR (catalog_code IS NOT NULL AND catalog_version IS NOT NULL)
    ),
    CONSTRAINT private_template_title_nonempty CHECK (length(trim(title)) > 0)
);
CREATE UNIQUE INDEX uq_private_template_catalog_origin
    ON workspace_private_templates(workspace_id, catalog_code)
    WHERE catalog_code IS NOT NULL;
CREATE INDEX idx_private_templates_workspace ON workspace_private_templates(workspace_id, kind, id);
